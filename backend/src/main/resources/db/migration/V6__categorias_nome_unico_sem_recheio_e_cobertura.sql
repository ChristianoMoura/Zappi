-- Zappi: categorias do cardápio, nome único do produto e fim de recheio e cobertura (ZAP-136, ZAP-137).
-- Mudança fora do dicionário de dados da Atividade #14 (registro na ZAP-83 e na seção 17 do
-- context.md): tabela nova `categoria`, coluna nova `produto.categoria_id`, saída de
-- `produto.sabor`, `item_pedido.recheio` e `item_pedido.cobertura`, e `item_pedido.observacao`
-- com 600 caracteres.
--
-- Nada se perde: o sabor vira parte do nome do produto, e o recheio e a cobertura dos pedidos
-- antigos vão para o começo da observação do item. Fazer backup manual do Supabase antes do
-- deploy (ele não faz backup automático no plano gratuito).

-- ---------------------------------------------------------------------------------------------
-- 1. Categorias, na ordem definida pela Lídia. Exclusão lógica (ativo = FALSE), como no produto
--    (RN14). O nome não se repete entre as ativas da loja, sem diferenciar maiúsculas (RN01).
-- ---------------------------------------------------------------------------------------------
CREATE TABLE categoria (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    estabelecimento_id BIGINT      NOT NULL,
    nome               VARCHAR(60) NOT NULL,
    ordem              INTEGER     NOT NULL,
    ativo              BOOLEAN     NOT NULL DEFAULT TRUE,
    criado_em          TIMESTAMPTZ NOT NULL DEFAULT now(),
    atualizado_em      TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT fk_categoria_estabelecimento FOREIGN KEY (estabelecimento_id) REFERENCES estabelecimento (id)
);

CREATE UNIQUE INDEX uk_categoria_nome_ativa ON categoria (estabelecimento_id, lower(nome)) WHERE ativo;
CREATE INDEX idx_categoria_estabelecimento ON categoria (estabelecimento_id, ativo, ordem);

ALTER TABLE categoria ENABLE ROW LEVEL SECURITY;

-- ---------------------------------------------------------------------------------------------
-- 2. Categorias dos produtos que já existem, ativos e excluídos: uma por nome de produto em
--    cada loja, com a regra de plural() do cardápio (frontend/src/cardapio/regrasCardapio.js, até
--    a ZAP-140): termina em vogal simples ganha "s" ("Bolo" vira "Bolos"); "Pão", "Pastel" e
--    "Café" ficam como estão. Nome vazio vira "Outros", e o nome é cortado em 60 caracteres.
--    Nomes que só mudam nas maiúsculas ficam numa categoria só. Ordem alfabética.
-- ---------------------------------------------------------------------------------------------
CREATE TEMPORARY TABLE categoria_do_produto ON COMMIT DROP AS
SELECT id AS produto_id,
       estabelecimento_id,
       btrim(left(COALESCE(NULLIF(
           CASE WHEN btrim(nome) ~* '[aeiou]$' AND btrim(nome) !~* '[ãõ][oe]$' THEN btrim(nome) || 's'
                ELSE btrim(nome)
           END, ''), 'Outros'), 60)) AS nome
FROM produto;

INSERT INTO categoria (estabelecimento_id, nome, ordem)
SELECT estabelecimento_id,
       min(nome),
       row_number() OVER (PARTITION BY estabelecimento_id ORDER BY lower(min(nome)), min(nome))
FROM categoria_do_produto
GROUP BY estabelecimento_id, lower(nome);

ALTER TABLE produto ADD COLUMN categoria_id BIGINT;

UPDATE produto p
SET categoria_id = c.id
FROM categoria_do_produto cp
JOIN categoria c ON c.estabelecimento_id = cp.estabelecimento_id AND lower(c.nome) = lower(cp.nome)
WHERE cp.produto_id = p.id;

ALTER TABLE produto
    ALTER COLUMN categoria_id SET NOT NULL,
    ADD CONSTRAINT fk_produto_categoria FOREIGN KEY (categoria_id) REFERENCES categoria (id);

CREATE INDEX idx_produto_categoria ON produto (categoria_id);

-- ---------------------------------------------------------------------------------------------
-- 3. Nome único do produto, sem o campo sabor, com a regra de nomeItem() do painel
--    (frontend/src/pedidos/regrasPedidos.js, até a ZAP-139): o produto "Bolo" vira "Bolo de " +
--    sabor em minúsculas; nos outros, o sabor vira o nome ("Salgado" + "Cento de coxinha" vira
--    "Cento de coxinha"). Até 150 caracteres, o limite da tela.
-- ---------------------------------------------------------------------------------------------
ALTER TABLE produto ALTER COLUMN nome TYPE VARCHAR(150);

UPDATE produto
SET nome = CASE WHEN nome = 'Bolo' THEN 'Bolo de ' || lower(sabor) ELSE sabor END;

ALTER TABLE produto DROP COLUMN sabor;

-- ---------------------------------------------------------------------------------------------
-- 4. Fim de recheio e cobertura: os valores dos pedidos antigos vão para o começo da observação
--    do item, seguidos da observação que já existia (ex.: "Recheio: brigadeiro. Cobertura:
--    ganache. Escrever Feliz aniversário"). Com até 100 caracteres em cada um e 300 na
--    observação, o texto cabe em 600; o limite da tela para itens novos continua 300.
-- ---------------------------------------------------------------------------------------------
ALTER TABLE item_pedido ALTER COLUMN observacao TYPE VARCHAR(600);

UPDATE item_pedido
SET observacao = concat_ws(' ',
        'Recheio: ' || NULLIF(rtrim(btrim(recheio), '. '), '') || '.',
        'Cobertura: ' || NULLIF(rtrim(btrim(cobertura), '. '), '') || '.',
        NULLIF(btrim(observacao), ''))
WHERE NULLIF(rtrim(btrim(recheio), '. '), '') IS NOT NULL
   OR NULLIF(rtrim(btrim(cobertura), '. '), '') IS NOT NULL;

ALTER TABLE item_pedido
    DROP COLUMN recheio,
    DROP COLUMN cobertura;
