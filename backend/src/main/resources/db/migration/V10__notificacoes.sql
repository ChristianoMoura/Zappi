-- Zappi: caixa de notificações do painel (ZAP-172, ZAP-173).
-- Tabela nova, fora do dicionário de dados da Atividade #14 (registro na ZAP-83 e, na
-- documentação, na ZAP-177).
--
-- Cada linha é um aviso para a Lídia sobre um pedido:
--   - tipo 1, Novo pedido: o pedido chegou pelo Portal do Cliente. Sem momento;
--   - tipo 2, Retirada próxima: gerado quando o painel consulta as notificações, porque o
--     backend gratuito do Render dorme sem acesso e não dá para usar tarefa agendada.
--     O momento diz qual aviso é (horário de São Paulo, decisão de 14/11/2026):
--       VESPERA    → pedido Novo, na véspera, a partir das 8h;
--       NO_DIA     → no dia da retirada, a partir das 8h;
--       DUAS_HORAS → 2 horas antes, pedidos Confirmado, Em produção ou Concluído.
--
-- Sem texto e sem dado pessoal (RN17): o texto é montado na leitura, a partir do pedido,
-- então a anonimização do cliente não deixa nada para trás aqui.
-- O mesmo aviso não é criado duas vezes para o mesmo pedido: a restrição única trata o
-- momento nulo do tipo 1 como igual (NULLS NOT DISTINCT, PostgreSQL 15 ou mais novo).
--
-- Nada se perde: só acrescenta uma tabela. Os pedidos que já existem não ganham avisos de
-- pedido novo; os de retirada próxima aparecem quando o momento deles chegar.

CREATE TABLE notificacao (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    estabelecimento_id BIGINT      NOT NULL,
    pedido_id          BIGINT      NOT NULL,
    tipo               SMALLINT    NOT NULL,
    momento            VARCHAR(20),
    criado_em          TIMESTAMPTZ NOT NULL DEFAULT now(),
    vista_em           TIMESTAMPTZ,
    CONSTRAINT fk_notificacao_estabelecimento FOREIGN KEY (estabelecimento_id) REFERENCES estabelecimento (id),
    CONSTRAINT fk_notificacao_pedido FOREIGN KEY (pedido_id) REFERENCES pedido (id) ON DELETE CASCADE,
    -- 1-Novo pedido, 2-Retirada próxima.
    CONSTRAINT ck_notificacao_tipo CHECK (tipo BETWEEN 1 AND 2),
    -- O novo pedido não tem momento; a retirada próxima tem um dos três. O IS NOT NULL é
    -- necessário: com momento nulo, o IN dá "desconhecido" e o CHECK deixaria passar.
    CONSTRAINT ck_notificacao_momento CHECK (
        (tipo <> 1 OR momento IS NULL)
        AND (tipo <> 2 OR (momento IS NOT NULL AND momento IN ('VESPERA', 'NO_DIA', 'DUAS_HORAS')))
    ),
    -- Cada aviso uma vez por pedido e por momento (ZAP-172).
    CONSTRAINT uk_notificacao_pedido_tipo_momento UNIQUE NULLS NOT DISTINCT (pedido_id, tipo, momento)
);

-- Contar as não vistas (sino) e listar as recentes (caixinha) da loja.
CREATE INDEX idx_notificacao_estabelecimento ON notificacao (estabelecimento_id, vista_em, criado_em);

-- RLS como nas demais tabelas (seção 13.3 e ISO 27002 5.34): só o backend acessa.
ALTER TABLE notificacao ENABLE ROW LEVEL SECURITY;
