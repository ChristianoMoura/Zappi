-- Zappi: aceite dos termos de uso e da política de privacidade (ZAP-143, ZAP-145).
-- Mudança fora do dicionário de dados da Atividade #14 (registro na ZAP-83 e, na documentação,
-- na ZAP-150): tabela nova `aceite_termos` e coluna nova `cliente.consentimento_versao`.
--
-- Nada se perde: só acrescenta. Os clientes que já existem ficam com a versão nula, porque o
-- consentimento deles é anterior aos termos (RN16).

-- ---------------------------------------------------------------------------------------------
-- 1. Aceite da Lídia, gravado junto com o login (ISO 27002 5.34 e 8.16). Guarda o histórico: cada
--    aceite é um registro novo, com a versão dos textos, a data, o IP e o navegador. Sem UNIQUE em
--    (usuario_id, versao): marcar a caixa de novo, em outro aparelho, vira mais uma prova do aceite.
-- ---------------------------------------------------------------------------------------------
CREATE TABLE aceite_termos (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id BIGINT      NOT NULL,
    versao     INTEGER     NOT NULL,
    aceito_em  TIMESTAMPTZ NOT NULL DEFAULT now(),
    ip_origem  VARCHAR(45),
    user_agent VARCHAR(255),
    CONSTRAINT fk_aceite_termos_usuario FOREIGN KEY (usuario_id) REFERENCES usuario (id),
    CONSTRAINT ck_aceite_termos_versao CHECK (versao > 0)
);

CREATE INDEX idx_aceite_termos_usuario ON aceite_termos (usuario_id, aceito_em);

ALTER TABLE aceite_termos ENABLE ROW LEVEL SECURITY;

-- ---------------------------------------------------------------------------------------------
-- 2. Versão dos textos que o cliente aceitou ao ser gravado (RN16). Nula nos clientes anteriores
--    aos termos.
-- ---------------------------------------------------------------------------------------------
ALTER TABLE cliente
    ADD COLUMN consentimento_versao INTEGER,
    ADD CONSTRAINT ck_cliente_consentimento_versao CHECK (consentimento_versao IS NULL OR consentimento_versao > 0);
