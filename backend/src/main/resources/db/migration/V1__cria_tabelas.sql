-- Zappi: tabelas do MVP (ZAP-72), conforme a seção 13 do context.md.
-- Datas em TIMESTAMPTZ e valores em NUMERIC(10,2). Migrações só para frente:
-- uma correção é sempre uma nova migração.

CREATE TABLE estabelecimento (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome              VARCHAR(100) NOT NULL,
    slug              VARCHAR(60)  NOT NULL,
    descricao         VARCHAR(500),
    telefone_whatsapp VARCHAR(13)  NOT NULL,
    email_contato     VARCHAR(150),
    cep               CHAR(8),
    logradouro        VARCHAR(150),
    numero            VARCHAR(10),
    complemento       VARCHAR(60),
    bairro            VARCHAR(80),
    cidade            VARCHAR(80),
    uf                CHAR(2),
    ativo             BOOLEAN      NOT NULL DEFAULT TRUE,
    criado_em         TIMESTAMPTZ  NOT NULL DEFAULT now(),
    atualizado_em     TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT uk_estabelecimento_slug UNIQUE (slug)
);

CREATE TABLE usuario (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    estabelecimento_id BIGINT       NOT NULL,
    nome               VARCHAR(100) NOT NULL,
    email              VARCHAR(150) NOT NULL,
    senha_hash         VARCHAR(60)  NOT NULL,
    ativo              BOOLEAN      NOT NULL DEFAULT TRUE,
    ultimo_login_em    TIMESTAMPTZ,
    criado_em          TIMESTAMPTZ  NOT NULL DEFAULT now(),
    atualizado_em      TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT uk_usuario_email UNIQUE (email),
    CONSTRAINT fk_usuario_estabelecimento FOREIGN KEY (estabelecimento_id) REFERENCES estabelecimento (id)
);

-- Tabela de domínio com valores fixos.
CREATE TABLE unidade_medida (
    id             SMALLINT    PRIMARY KEY,
    sigla          VARCHAR(5)  NOT NULL,
    descricao      VARCHAR(30) NOT NULL,
    permite_fracao BOOLEAN     NOT NULL,
    CONSTRAINT uk_unidade_medida_sigla UNIQUE (sigla)
);

