CREATE TABLE produto (
    id                     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    estabelecimento_id     BIGINT        NOT NULL,
    unidade_medida_id      SMALLINT      NOT NULL,
    nome                   VARCHAR(100)  NOT NULL,
    sabor                  VARCHAR(100)  NOT NULL,
    descricao              VARCHAR(500),
    preco                  NUMERIC(10,2) NOT NULL,
    foto_caminho           VARCHAR(255),
    foto_texto_alternativo VARCHAR(150),
    ativo                  BOOLEAN       NOT NULL DEFAULT TRUE,
    criado_em              TIMESTAMPTZ   NOT NULL DEFAULT now(),
    atualizado_em          TIMESTAMPTZ   NOT NULL DEFAULT now(),
    CONSTRAINT fk_produto_estabelecimento FOREIGN KEY (estabelecimento_id) REFERENCES estabelecimento (id),
    CONSTRAINT fk_produto_unidade_medida FOREIGN KEY (unidade_medida_id) REFERENCES unidade_medida (id),
    CONSTRAINT ck_produto_preco CHECK (preco > 0),
    -- NBR 17225 5.9.1: toda foto tem texto alternativo.
    CONSTRAINT ck_produto_foto_texto_alternativo CHECK (foto_caminho IS NULL OR foto_texto_alternativo IS NOT NULL)
);

CREATE TABLE cliente (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    estabelecimento_id BIGINT       NOT NULL,
    nome               VARCHAR(100) NOT NULL,
    telefone_whatsapp  VARCHAR(13)  NOT NULL,
    consentimento_lgpd BOOLEAN      NOT NULL,
    consentimento_em   TIMESTAMPTZ  NOT NULL,
    anonimizado_em     TIMESTAMPTZ,
    criado_em          TIMESTAMPTZ  NOT NULL DEFAULT now(),
    atualizado_em      TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT fk_cliente_estabelecimento FOREIGN KEY (estabelecimento_id) REFERENCES estabelecimento (id),
    CONSTRAINT uk_cliente_telefone UNIQUE (estabelecimento_id, telefone_whatsapp),
    -- Alvo da FK composta de pedido (consistência de tenant, ZAP-64).
    CONSTRAINT uk_cliente_id_estabelecimento UNIQUE (id, estabelecimento_id),
    -- LGPD: o cliente só é gravado com consentimento (RN16).
    CONSTRAINT ck_cliente_consentimento CHECK (consentimento_lgpd = TRUE)
);

CREATE TABLE pedido (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    estabelecimento_id BIGINT        NOT NULL,
    cliente_id         BIGINT        NOT NULL,
    numero             INTEGER       NOT NULL,
    status             SMALLINT      NOT NULL,
    data_retirada      DATE          NOT NULL,
    observacao         VARCHAR(500),
    motivo_recusa      VARCHAR(500),
    valor_total        NUMERIC(10,2) NOT NULL,
    criado_em          TIMESTAMPTZ   NOT NULL DEFAULT now(),
    confirmado_em      TIMESTAMPTZ,
    producao_em        TIMESTAMPTZ,
    recusado_em        TIMESTAMPTZ,
    concluido_em       TIMESTAMPTZ,
    atualizado_em      TIMESTAMPTZ   NOT NULL DEFAULT now(),
    CONSTRAINT fk_pedido_estabelecimento FOREIGN KEY (estabelecimento_id) REFERENCES estabelecimento (id),
    -- O cliente precisa ser do mesmo estabelecimento do pedido (ZAP-64, item 14.6).
    CONSTRAINT fk_pedido_cliente FOREIGN KEY (cliente_id, estabelecimento_id) REFERENCES cliente (id, estabelecimento_id),
    CONSTRAINT uk_pedido_numero UNIQUE (estabelecimento_id, numero),
    -- 1-Novo, 2-Confirmado, 3-Em produção, 4-Concluído, 5-Recusado (RN03).
    CONSTRAINT ck_pedido_status CHECK (status BETWEEN 1 AND 5),
    -- Recusar ou cancelar exige motivo (RN05).
    CONSTRAINT ck_pedido_motivo_recusa CHECK (status <> 5 OR motivo_recusa IS NOT NULL)
);

CREATE TABLE item_pedido (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pedido_id      BIGINT        NOT NULL,
    produto_id     BIGINT        NOT NULL,
    quantidade     NUMERIC(8,3)  NOT NULL,
    preco_unitario NUMERIC(10,2) NOT NULL,
    subtotal       NUMERIC(10,2) NOT NULL,
    recheio        VARCHAR(100),
    cobertura      VARCHAR(100),
    observacao     VARCHAR(300),
    CONSTRAINT fk_item_pedido_pedido FOREIGN KEY (pedido_id) REFERENCES pedido (id) ON DELETE CASCADE,
    CONSTRAINT fk_item_pedido_produto FOREIGN KEY (produto_id) REFERENCES produto (id),
    CONSTRAINT ck_item_pedido_quantidade CHECK (quantidade > 0)
);

CREATE TABLE mensagem_whatsapp (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pedido_id        BIGINT       NOT NULL,
    tipo             SMALLINT     NOT NULL,
    telefone_destino VARCHAR(13)  NOT NULL,
    conteudo         TEXT         NOT NULL,
    status           SMALLINT     NOT NULL,
    id_externo       VARCHAR(100),
    criado_em        TIMESTAMPTZ  NOT NULL DEFAULT now(),
    enviado_em       TIMESTAMPTZ,
    CONSTRAINT fk_mensagem_whatsapp_pedido FOREIGN KEY (pedido_id) REFERENCES pedido (id) ON DELETE CASCADE,
    -- 1-Confirmação, 2-Recusa, 3-Pronto para retirada.
    CONSTRAINT ck_mensagem_whatsapp_tipo CHECK (tipo BETWEEN 1 AND 3),
    -- 1-Pendente, 2-Enviada, 3-Falha.
    CONSTRAINT ck_mensagem_whatsapp_status CHECK (status BETWEEN 1 AND 3)
);

-- Trilha de auditoria (ISO 27002 8.16). Os ids ficam nulos em falha de login com e-mail inexistente.
CREATE TABLE log_auditoria (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    estabelecimento_id BIGINT,
    usuario_id         BIGINT,
    acao               VARCHAR(40)  NOT NULL,
    entidade           VARCHAR(40),
    entidade_id        BIGINT,
    email_informado    VARCHAR(150),
    ip_origem          VARCHAR(45),
    user_agent         VARCHAR(255),
    detalhes           JSONB,
    criado_em          TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT fk_log_auditoria_estabelecimento FOREIGN KEY (estabelecimento_id) REFERENCES estabelecimento (id),
    CONSTRAINT fk_log_auditoria_usuario FOREIGN KEY (usuario_id) REFERENCES usuario (id)
);

-- Índices das consultas mais usadas.
CREATE INDEX idx_produto_estabelecimento ON produto (estabelecimento_id, ativo);
CREATE INDEX idx_pedido_estabelecimento_status ON pedido (estabelecimento_id, status);
CREATE INDEX idx_item_pedido_pedido ON item_pedido (pedido_id);
CREATE INDEX idx_mensagem_whatsapp_pedido ON mensagem_whatsapp (pedido_id);
-- Contagem de falhas de login por e-mail para o bloqueio do RF02 (ZAP-85).
CREATE INDEX idx_log_auditoria_email ON log_auditoria (email_informado, criado_em);
CREATE INDEX idx_log_auditoria_estabelecimento ON log_auditoria (estabelecimento_id, criado_em);

